    <h4>二、看板页（日常最常用）</h4>

    <h5>2.1 看板怎么看</h5>
    <ul>
      <li>看板<b>按区域分节</b>（左侧竖排区域徽标），区域顺序与现场平面图一致（4C→4B→4A→3C…），库位号自然排序。</li>
      <li>每个库位一张卡片：卡头是<b>库位号</b>（后跟备注，如子位名）；右侧标签表示状态——绿色「库存 X 批 · Y 件」、灰色「空闲」、红色「未登记 / 已停用 / 不可存放」。</li>
      <li>有货卡片下方是<b>批次迷你格</b>（最多 20 格）：<b>颜色=该批状态</b>（绿正常 / 黄预警 / 红严重），<b>格内数字=该批件数</b>。超过 20 批显示「超出20批 X 批」标签。</li>
    </ul>

    <h5>2.2 每个按钮干什么</h5>
    <ul>
      <li><b>同步最新数据</b>：先从钉钉「出入库流水表」拉最新（已配置时），再刷新看板。看板虽每 30 秒自动刷新本地，但钉钉新记的行要同步才会进来——急看就点它。</li>
      <li><b>记一笔</b>：记账入口，见第三节。</li>
      <li><b>扫码</b>（仅手机显示，需在钉钉内）：扫<b>库位二维码</b> → 直接弹该库位明细；扫<b>产品条码</b>（码内容=图号）→ 打开产品查询。</li>
      <li><b>产品查询</b>：输入图号（支持搜索联想，含钉钉表全部 583 个图号），显示该产品现有总量、分布在几个库位、每批次停放天数（按停放时间降序），底部有先进先出排产提示。</li>
      <li><b>导出</b>：一键下载 Excel 库存清单（含产品/批次/库位/区域/件数/入库时间/停放天数/状态 + 合计行）。</li>
      <li>搜索框：支持<b>库位号 / 批次号 / 区域 / 产品图号</b>实时过滤。</li>
      <li>统计标签（在库批次 / 正常 / 预警 / 严重）：<b>可点击</b>，按状态筛选库位；再点一次取消筛选。</li>
      <li>库位明细弹窗：显示共几批几件、区域/备注/数据日，明细按<b>停放时间倒序（先进先出）</b>排列，含产品图号、批次号、数量、停放天数、入位日期、状态圆点。手机端自动变为卡片列表。</li>
    </ul>

    <h4>三、记一笔（核心操作）</h4>
    <p>点绿色「<b>记一笔</b>」，弹窗内三步完成。<b>谁经手谁署名</b>。</p>

    <h5>3.1 入库</h5>
    <ol>
      <li>操作类型选「<b>入库</b>」；</li>
      <li>选<b>库位</b>（只能选已登记、已启用的库位，按区域分组，可输入搜索）；</li>
      <li>填/选<b>产品图号</b>（优先从钉钉表图号下拉中搜索选择，钉钉不可用时手填）；</li>
      <li>选<b>操作时间</b>——<b>批次号由该时间自动生成</b>（格式 <code>MMDD-HHmm</code>，弹窗内实时预览），该时间就是批次的入位时间；</li>
      <li>填<b>件数</b>、录入人（可从历史带出）、备注（选填）→ 点「<b>记入台账</b>」，看板即时刷新。</li>
    </ol>
    <p>规则：同库位、同图号、同批次再入库 → <b>只累加件数，停放天数不重算</b>。</p>

    <h5>3.2 出库</h5>
    <ol>
      <li>操作类型选「<b>出库</b>」；</li>
      <li>选<b>有货库位</b>（下拉直接显示每库位几批几件）；</li>
      <li>选<b>产品图号</b> → 选<b>批次</b>——系统<b>已默认选停放最久的那批（先进先出）</b>，下拉里每批标注「余 X 件 · 停放 Y 天」，想动哪批就选哪批；</li>
      <li>填件数（上限=该批现有件数，<b>超出会被拒绝</b>）→ 记入台账。</li>
    </ol>

    <h5>3.3 转移</h5>
    <p>
      与出库类似，多选一个<b>目标库位</b>（不能与源库位相同）。规则：<b>产品在新库位停放天数重新起算</b>；回写钉钉表时自动拆成「出库+入库」两行。
    </p>

    <h4>四、设置页（管理员）</h4>

    <h5>4.1 预警阈值</h5>
    <p>「黄色预警（停放 ≥）X 天」「红色预警（停放 ≥）Y 天」，默认 3 / 5 天，保存后<b>看板颜色全局即时生效</b>。</p>

    <h5>4.2 库位登记</h5>
    <ul>
      <li>表格内<b>区域、备注可直接改</b>，改完自动保存；<b>启用开关</b>停用后不可再录入该库位，历史数据保留。</li>
      <li>单个添加：填库位号、区域、备注 → 添加。</li>
      <li><b>批量导入</b>：文本框每行一条，格式 <code>库位号,区域,备注</code>（如 <code>1B1-半成品,白区,大件区</code>），点批量导入；重复或格式不对的行自动跳过。</li>
      <li><b>生成库位二维码标签</b>：为全部已启用库位生成二维码标签页 → 打印 → 沿虚线裁开贴到现场库位（不干胶纸最佳）。<b>二维码内容=库位号</b>，贴好后手机钉钉扫一下即开该库位明细。</li>
    </ul>

    <h5>4.3 钉钉同步（录入端）</h5>
    <p>
      配置项：AppKey、AppSecret、操作人 unionId、表格 baseId、流水表名、企业 CorpId、应用 AgentId（后两项为手机扫码用）、自动同步间隔（分钟，<b>0=关闭自动同步只手动</b>）、「以钉钉为准」<b>镜像模式</b>开关（默认开）、「锁定录入人」开关。填好点<b>保存配置</b>即生效；<b>立即同步</b>可手动拉一次并在下方显示结果（含跳过行清单及原因）。
    </p>
    <p>状态行显示：上次同步时间、表格行数、本次新增、累计入账、最近错误。</p>
    <p>
      同步口径：<b>按钉钉行 ID 去重</b>，重复点同步不会重复入账；镜像模式下表格删行/改行最迟 2 分钟在看板生效（网页端刚记未落表的笔有 10 分钟保护期）。
    </p>

    <h5>4.4 台账审计</h5>
    <p>
      显示最近每笔流水：序号、日期、类型（入/出/转移）、内容、录入人、操作时间。<b>台账只追加不修改</b>（<code>backend/data/snapshots.jsonl</code>），每笔永久留档；库存=流水重放结果，随时可审计。
    </p>
